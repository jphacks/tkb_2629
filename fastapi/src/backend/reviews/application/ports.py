from __future__ import annotations

from collections.abc import Callable, Sequence
from datetime import datetime
from types import TracebackType
from typing import Protocol, Self

from ..domain.entities import PageReview
from .results import AnalysisPreview, EmotionSummary, PagePopularity, ReadingScope

AnalysisKey = tuple[int, int]


class ReadingGateway(Protocol):
    def resolve(self, user_id: int, book_id: int, iteration: int | None) -> ReadingScope: ...
    def record_progress(self, scope: ReadingScope, page: int) -> ReadingScope: ...
    def reading_ids(self, book_id: int, *, latest_only: bool) -> list[int]: ...


class AnalysisGateway(Protocol):
    def analyze(self, review_id: int, revision: int, text: str) -> AnalysisPreview: ...
    def previews(self, references: Sequence[AnalysisKey]) -> dict[AnalysisKey, AnalysisPreview]: ...
    def summarize(self, references: Sequence[AnalysisKey]) -> EmotionSummary: ...


class ReviewRepository(Protocol):
    def get(self, review_id: int, *, lock: bool = False) -> PageReview | None: ...
    def find(self, reading_id: int, page: int, *, lock: bool = False) -> PageReview | None: ...
    def list(self, reading_id: int, limit: int, offset: int) -> list[PageReview]: ...
    def add(self, review: PageReview) -> PageReview: ...
    def save(self, review: PageReview) -> None: ...
    def save_visibility(self, review: PageReview) -> None: ...
    def save_spoilers(self, review: PageReview) -> None: ...
    def analysis_references(self, reading_ids: Sequence[int]) -> list[AnalysisKey]: ...
    def page_popularity(self, reading_ids: Sequence[int]) -> list[PagePopularity]: ...


class ReviewUnitOfWork(Protocol):
    @property
    def reviews(self) -> ReviewRepository: ...
    @property
    def readings(self) -> ReadingGateway: ...
    def __enter__(self) -> Self: ...
    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...
    def commit(self) -> None: ...


UnitOfWorkFactory = Callable[[], ReviewUnitOfWork]


class Clock(Protocol):
    def now(self) -> datetime: ...
